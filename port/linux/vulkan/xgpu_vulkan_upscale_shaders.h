/*
XGPU_VULKAN_UPSCALE_SHADERS.H

The frame upscaling's compute programs as SPIR-V (display.upscaler,
docs/prism_plugin.md), generated by tools/vulkan_upscale_shaders.py:
FidelityFX Super Resolution 3.1's upscaler passes (port/third_party/
fidelityfx-fsr3, AMD's GLSL, MIT), whose bindings are their pass files' own
(set 0, the samplers at bindings 1000 and 1001), run by xgpu_vulkan_fsr3.c;
and the renderer's own pass that gives an upscaler the view's colour,
depth, motion and reactive mask (xgpu_vulkan_upscale.c).
*/

#ifndef XGPU_VULKAN_UPSCALE_SHADERS_H
#define XGPU_VULKAN_UPSCALE_SHADERS_H

#include <stddef.h>
#include <stdint.h>

enum xgpu_vulkan_upscale_program_id
{
	XGPU_VULKAN_FSR3_PREPARE_INPUTS,
	XGPU_VULKAN_FSR3_LUMA_PYRAMID,
	XGPU_VULKAN_FSR3_SHADING_CHANGE_PYRAMID,
	XGPU_VULKAN_FSR3_SHADING_CHANGE,
	XGPU_VULKAN_FSR3_PREPARE_REACTIVITY,
	XGPU_VULKAN_FSR3_LUMA_INSTABILITY,
	XGPU_VULKAN_FSR3_ACCUMULATE,
	XGPU_VULKAN_FSR3_ACCUMULATE_SHARPEN,
	XGPU_VULKAN_FSR3_RCAS,
	/* the view's inputs for an upscaler (xgpu_vulkan_upscale.c) */
	XGPU_VULKAN_UPSCALE_INPUTS,
	XGPU_VULKAN_UPSCALE_PROGRAM_COUNT
};

struct xgpu_vulkan_upscale_program
{
	const uint32_t *words;
	size_t count;
};

extern const struct xgpu_vulkan_upscale_program xgpu_vulkan_upscale_programs[XGPU_VULKAN_UPSCALE_PROGRAM_COUNT];

#endif
