#!/usr/bin/env python3
"""Build PRISM v4's in-game baker's compute shaders and PRISM Raster's light pass (port/linux/vulkan/
xgpu_vulkan_bake.c) from their GLSL (port/linux/vulkan/xgpu_vulkan_bake_glsl.inc).

Run with a C preprocessor (cc), glslangValidator and spirv-val on PATH:
    python3 tools/vulkan_bake_shaders.py
The generated C embeds SPIR-V; the game does not need a shader compiler. The sources share their scene's
access (the file's BAKE_COMMON), which the C preprocessor puts in each before its strings are read.
--check verifies that the checked-in words still match their source.
"""

from __future__ import annotations

import argparse
import ast
import re
import shutil
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "port/linux/vulkan/xgpu_vulkan_bake_glsl.inc"
OUTPUT = ROOT / "port/linux/vulkan/xgpu_vulkan_bake_shaders.c"
NAMES = ("setup", "lightmap", "mask", "importance", "volume", "raster", "compact", "reflection", "exposure", "lampmask")
DECLARATION = re.compile(r"static const char (\w+)_source\[\]\s*=\s*((?:\s|\"(?:\\.|[^\"\\])*\")+);", re.S)
STRINGS = re.compile(r'"(?:\\.|[^"\\])*"')


def sources() -> dict[str, str]:
    cc = shutil.which("cc") or shutil.which("clang") or shutil.which("gcc")
    if not cc:
        raise SystemExit("no C preprocessor (cc) on PATH")
    text = subprocess.run([cc, "-E", "-P", "-x", "c", str(SOURCE)], check=True, capture_output=True,
                          text=True).stdout
    found = {}
    for match in DECLARATION.finditer(text):
        found[match.group(1)] = "".join(ast.literal_eval(s) for s in STRINGS.findall(match.group(2)))
    missing = [name for name in NAMES if name not in found]
    if missing:
        raise SystemExit(f"{SOURCE}: no {', '.join(name + '_source' for name in missing)}")
    return {name: found[name] for name in NAMES}


def compile_words(name: str, glsl: str) -> list[int]:
    with tempfile.TemporaryDirectory(dir=ROOT / "build") as folder:
        spv = Path(folder) / f"{name}.spv"
        result = subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "--stdin", "-S", "comp",
                                 "-o", str(spv)], input=glsl.encode(), capture_output=True)
        if result.returncode:
            raise SystemExit(f"{name}: {result.stdout.decode()}{result.stderr.decode()}")
        subprocess.run(["spirv-val", "--target-env", "vulkan1.3", str(spv)], check=True)
        data = spv.read_bytes()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def generate() -> str:
    lines = ["/* Generated by tools/vulkan_bake_shaders.py from xgpu_vulkan_bake_glsl.inc. Do not edit. */", "",
             '#include "xgpu_vulkan_bake_shaders.h"', ""]
    for name, glsl in sources().items():
        words = compile_words(name, glsl)
        lines.append(f"const uint32_t xgpu_vulkan_bake_{name}_words[] =")
        lines.append("{")
        for start in range(0, len(words), 8):
            lines.append("\t" + " ".join(f"0x{w:08x}," for w in words[start:start + 8]))
        lines.append("};")
        lines.append(f"const size_t xgpu_vulkan_bake_{name}_count = sizeof(xgpu_vulkan_bake_{name}_words) / "
                     f"sizeof(xgpu_vulkan_bake_{name}_words[0]);")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    (ROOT / "build").mkdir(exist_ok=True)
    text = generate()
    if arguments.check:
        if OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT} differs from its source: run tools/vulkan_bake_shaders.py")
        return
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
