#!/usr/bin/env python3
"""Build the Vulkan ray tracing compute shaders (display.prism_rt) from its GLSL
(port/linux/vulkan/xgpu_vulkan_rt_glsl.inc).

Run with glslangValidator and spirv-val on PATH:
    python3 tools/vulkan_rt_shaders.py
The generated C embeds SPIR-V; the game does not need a shader compiler.
--check verifies that the checked-in words still match their source.
"""

from __future__ import annotations

import argparse
import ast
import re
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "port/linux/vulkan/xgpu_vulkan_rt_glsl.inc"
OUTPUT = ROOT / "port/linux/vulkan/xgpu_vulkan_rt_shaders.c"
DECLARATION = re.compile(r"static const char (\w+)_source\[\]\s*=\s*((?:\s|\"(?:\\.|[^\"\\])*\")+);", re.S)
STRINGS = re.compile(r'"(?:\\.|[^"\\])*"')


def sources() -> dict[str, str]:
    text = SOURCE.read_text()
    found = {}
    for match in DECLARATION.finditer(text):
        found[match.group(1)] = "".join(ast.literal_eval(s) for s in STRINGS.findall(match.group(2)))
    if "trace" not in found or "resolve" not in found:
        raise SystemExit(f"{SOURCE}: no trace_source or resolve_source")
    return found


def compile_words(name: str, glsl: str) -> list[int]:
    with tempfile.TemporaryDirectory(dir=ROOT / "build") as folder:
        spv = Path(folder) / f"{name}.spv"
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "--stdin", "-S", "comp",
                        "-o", str(spv)], input=glsl.encode(), check=True, capture_output=True)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.3", str(spv)], check=True)
        data = spv.read_bytes()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def generate() -> str:
    lines = ["/* Generated by tools/vulkan_rt_shaders.py from xgpu_vulkan_rt_glsl.inc. Do not edit. */", "",
             '#include "xgpu_vulkan_rt_shaders.h"', ""]
    for name, glsl in sources().items():
        words = compile_words(name, glsl)
        lines.append(f"const uint32_t xgpu_vulkan_rt_{name}_words[] =")
        lines.append("{")
        for start in range(0, len(words), 8):
            lines.append("\t" + " ".join(f"0x{w:08x}," for w in words[start:start + 8]))
        lines.append("};")
        lines.append(f"const size_t xgpu_vulkan_rt_{name}_count = sizeof(xgpu_vulkan_rt_{name}_words) / "
                     f"sizeof(xgpu_vulkan_rt_{name}_words[0]);")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    (ROOT / "build").mkdir(exist_ok=True)
    text = generate()
    if arguments.check:
        if OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT} differs from its source: run tools/vulkan_rt_shaders.py")
        return
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
