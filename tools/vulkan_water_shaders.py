#!/usr/bin/env python3
"""Build the terrain overhaul's water layer's compute shader (T7, port/linux/vulkan/xgpu_vulkan_water.c) from its GLSL
(port/linux/vulkan/xgpu_vulkan_water.glsl).

Run with glslangValidator and spirv-val on PATH:
    python3 tools/vulkan_water_shaders.py
The generated C (port/linux/vulkan/xgpu_vulkan_water_shaders.c) embeds SPIR-V; the game does not need a shader
compiler. --check verifies that the checked-in words still match their source.
"""

from __future__ import annotations

import argparse
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "port/linux/vulkan/xgpu_vulkan_water.glsl"
OUTPUT = ROOT / "port/linux/vulkan/xgpu_vulkan_water_shaders.c"
NAMES = ("composite",)


def compile_words(name: str, glsl: str) -> list[int]:
    with tempfile.TemporaryDirectory(dir=ROOT / "build") as folder:
        spv = Path(folder) / f"{name}.spv"
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.2", "--stdin", "-S", "comp",
                        "-o", str(spv)], input=glsl.encode(), check=True, capture_output=True)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.2", str(spv)], check=True)
        data = spv.read_bytes()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def generate() -> str:
    glsl = SOURCE.read_text()
    lines = ["/* Generated by tools/vulkan_water_shaders.py from xgpu_vulkan_water.glsl. Do not edit. */", "",
             '#include "xgpu_vulkan_water_shaders.h"', ""]
    for name in NAMES:
        try:
            words = compile_words(name, glsl)
        except subprocess.CalledProcessError as error:
            raise SystemExit((error.stdout or b"").decode() + (error.stderr or b"").decode())
        lines.append(f"const uint32_t xgpu_vulkan_water_{name}_words[] =")
        lines.append("{")
        for start in range(0, len(words), 8):
            lines.append("\t" + " ".join(f"0x{w:08x}," for w in words[start:start + 8]))
        lines.append("};")
        lines.append(f"const size_t xgpu_vulkan_water_{name}_count = sizeof(xgpu_vulkan_water_{name}_words) / "
                     f"sizeof(xgpu_vulkan_water_{name}_words[0]);")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    (ROOT / "build").mkdir(exist_ok=True)
    text = generate()
    if arguments.check:
        if OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT} differs from its source: run tools/vulkan_water_shaders.py")
        return
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
